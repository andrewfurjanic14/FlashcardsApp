CREATE TABLE Decks (
	Id INT IDENTITY PRIMARY KEY,
	Name NVARCHAR(50) NOT NULL
);

CREATE TABLE Flashcards (
	Id INT IDENTITY PRIMARY KEY,
	DeckId INT,
	Question NVARCHAR(500) NOT NULL,
	Answer NVARCHAR(500) NOT NULL,

	CONSTRAINT FK_Flashcards_Decks
		FOREIGN KEY (DeckId)
		REFERENCES Decks(Id)
		ON DELETE CASCADE
);